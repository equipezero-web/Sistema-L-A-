import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const sql=read('supabase/sql/saas_checkout_brick_readiness_20261116.sql');
const backend=read('supabase/functions/saas-transparent-checkout/index.ts');
const oauth=read('supabase/functions/saas-merchant-oauth/index.ts');
const browser=read('assets/js/transparent-payment.js');
const store=read('store/loja-virtual.html');
const cart=read('assets/js/virtual-storefront.js');
test('Public seller key saved only by service role and checkout activation remains tenant scoped',()=>{
 assert.match(sql,/checkout_public_key text/);
 assert.match(sql,/p_public_key !~ '\^\(APP_USR\|TEST\)/);
 assert.match(sql,/provider_account_id=p_account_id/);
 assert.match(sql,/revoke all on function public\.saas_merchant_checkout_save_public_key\(uuid,text,text\) from public,anon,authenticated/);
 assert.match(sql,/grant execute on function public\.saas_merchant_checkout_save_public_key\(uuid,text,text\) to service_role/);
 assert.match(sql,/private\.saas_online_order_activation a on a\.tenant_id=t\.id and a\.enabled/);
 assert.match(sql,/s\.slug=p_slug and s\.template_code='virtual_store' and t\.active/);
 assert.match(sql,/c\.token_expires_at>now\(\)\+interval '30 seconds'/);
 assert.match(oauth,/tokens\?\.public_key/);
 assert.match(oauth,/saas_merchant_checkout_save_public_key/);
 assert.doesNotMatch(store,/APP_USR-|MP_MERCHANT_CLIENT_SECRET|SUPABASE_SERVICE_ROLE_KEY/);
});
test('Readiness keeps production off and requires double-gated TEST seller sandbox',()=>{
 assert.match(backend,/PAYMENT_PROCESSING_IMPLEMENTED=false/);
 assert.match(backend,/SAAS_TRANSPARENT_CHECKOUT_ENABLED/);
 assert.match(backend,/saas_transparent_checkout_readiness/);
 assert.match(backend,/if\(!sandboxReady\)/);
 assert.match(backend,/Cobranças bloqueadas até homologação/);
 assert.match(backend,/checkout_enabled:false/);
 assert.doesNotMatch(backend,/v1\/payments|fetch\("https:\/\/api\.mercadopago/);
});
test('Brick is deferred until explicit readiness and quote, not rendered automatically',()=>{
 assert.match(store,/id="paymentBrick_container" hidden/);
 assert.match(store,/id="transparentPaymentStatus"/);
 assert.match(store,/assets\/js\/transparent-payment\.js/);
 assert.match(browser,/data\.checkout_enabled===true&&validKey\(data\.public_key\)/);
 assert.match(browser,/!ready\.sandbox_only/);
 assert.match(browser,/quote\.currency!=='BRL'/);
 assert.match(browser,/sdk\.mercadopago\.com\/js\/v2/);
 assert.match(browser,/window\.MercadoPago\(ready\.public_key/);
 assert.match(browser,/locale:'pt-BR'/);
 assert.match(browser,/mp\.bricks\(\)\.create\('payment','paymentBrick_container',settings\)/);
 assert.match(browser,/onSubmit:async\(\{formData\}\)/);
 assert.match(browser,/controller\.unmount\(\)/);
 assert.match(cart,/la:cart-updated/);
 assert.match(cart,/la:quote-validated/);
 assert.doesNotMatch(browser,/access_token|service_role|client_secret|\/v1\/payments/);
 assert.doesNotThrow(()=>new vm.Script(browser.replace(/^import\s*\{[^}]+\}\s*from\s*'[^']+';\s*$/gm,'')));
});

test('Expired quotes unmount the payment Brick and invalidate pending render',()=>{
 assert.match(browser,/let quoteExpiryTimer=null/);
 assert.match(browser,/clearTimeout\(quoteExpiryTimer\)/);
 assert.match(browser,/expiresAt<=Date\.now\(\)/);
 assert.match(browser,/quoteExpiryTimer=setTimeout/);
 assert.match(browser,/void unmount\(\)/);
 assert.match(browser,/Cotação expirada/);
});
